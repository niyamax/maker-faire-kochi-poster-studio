"""Compile bundled Inter into portable poster-copy paths. Source license: licenses/Inter-OFL.txt."""
from pathlib import Path
import json
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
project=Path(__file__).resolve().parents[1]
root=project/'assets'/'fonts'
f=TTFont(root/'Inter.ttf')
if 'fvar' in f:
    f=instantiateVariableFont(f, {'wght':400}, inplace=False)
glyphs=f.getGlyphSet(); cmap=f.getBestCmap(); out={}
for c in ''.join(chr(n) for n in range(32,256))+'–—’‘“”•↗×':
    name=cmap.get(ord(c))
    if not name: continue
    pen=SVGPathPen(glyphs); glyphs[name].draw(pen)
    bounds=BoundsPen(glyphs); glyphs[name].draw(bounds)
    out[c]={'d':pen.getCommands(),'advance':f['hmtx'][name][0],'bounds':bounds.bounds}
(project/'src'/'data'/'copy-outlines.js').write_text('/** Bundled Inter, SIL OFL. Generated by scripts/build-copy-font.py. */\nexport const COPY_FONT='+json.dumps({'em':f['head'].unitsPerEm,'glyphs':out},separators=(',',':'))+';\n')
print(f'Compiled {len(out)} copy glyphs')
