import {readFile,writeFile} from 'node:fs/promises';

// Keep the browser and standalone scene renderer independent of asset fetches.
const artwork={};
for(const layout of ['long','border','square'])for(const colour of ['colour','black','white']){
  const filename=`MF_Kochi_Logo_${layout}${colour==='colour'?'':`_${colour}`}.svg`;
  const svg=await readFile(new URL(`../assets/logos/${filename}`,import.meta.url),'utf8');
  const [,width,height]=svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  artwork[`${layout}-${colour}`]={svg,width:Number(width),height:Number(height)};
}
await writeFile(new URL('../src/data/logo.js',import.meta.url),`// Generated by scripts/build-logos.mjs from assets/logos/*.svg.\nexport const LOGO_ARTWORK=${JSON.stringify(artwork)};\nexport const LOGO_DATA='data:image/svg+xml;charset=utf-8,'+encodeURIComponent(LOGO_ARTWORK['long-colour'].svg);\n`);
