"""Compile native Anton outlines for fixed-proportion editorial headings.

Source: assets/fonts/Anton-Regular.ttf; SIL OFL, licenses/Anton-OFL.txt.
Unlike the deformable display data, this preserves baseline, bearings, and
punctuation placement so one uniform scale reproduces the original typeface.
"""
from pathlib import Path
import json
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

root = Path(__file__).resolve().parents[1]
font = TTFont(root / 'assets/fonts/Anton-Regular.ttf')
glyph_set, cmap = font.getGlyphSet(), font.getBestCmap()
glyphs = {}
for char in ''.join(chr(n) for n in range(32, 256)) + '–—’‘“”•×':
    name = cmap.get(ord(char))
    if not name:
        continue
    path, bounds = SVGPathPen(glyph_set), BoundsPen(glyph_set)
    glyph_set[name].draw(path)
    glyph_set[name].draw(bounds)
    glyphs[char] = {'d': path.getCommands(), 'advance': font['hmtx'][name][0], 'bounds': bounds.bounds}
cap = getattr(font['OS/2'], 'sCapHeight', 0) or font['head'].unitsPerEm * .7
output = {'em': font['head'].unitsPerEm, 'capHeight': cap, 'glyphs': glyphs}
(root / 'src/data/display-outlines.js').write_text('/** Bundled Anton, SIL OFL. Generated by scripts/build-display-font.py. */\nexport const DISPLAY_FONT=' + json.dumps(output, separators=(',', ':')) + ';\n')
print(f'Compiled {len(glyphs)} native display glyphs')
