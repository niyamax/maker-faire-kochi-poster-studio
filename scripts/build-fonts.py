"""Compile licensed display fonts into deterministic, offline outline assets.

FontTools resolves composite glyphs and variable-font instances. Curve sampling
is fixed at build time, so every animation frame has identical SVG topology.
The emitted outlines are artwork geometry; source TTFs remain unmodified.
"""
from pathlib import Path
import hashlib
import json
import string

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.basePen import BasePen

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets' / 'fonts'
OUTPUT = ROOT / 'src' / 'data'
CHARS = string.ascii_letters + string.digits + string.punctuation + ' –—’“”'
FONTS = [
    ('dela', 'DelaGothicOne-Regular.ttf', {}, 'DelaGothicOne-OFL.txt', 'https://github.com/google/fonts/tree/main/ofl/delagothicone'),
    ('anton', 'Anton-Regular.ttf', {}, 'Anton-OFL.txt', 'https://github.com/google/fonts/tree/main/ofl/anton'),
    ('bricolage', 'BricolageGrotesque-variable.ttf', {'opsz': 96, 'wght': 800, 'wdth': 100}, 'BricolageGrotesque-OFL.txt', 'https://github.com/google/fonts/tree/main/ofl/bricolagegrotesque'),
    ('bowlby', 'BowlbyOne-Regular.ttf', {}, 'BowlbyOne-OFL.txt', 'https://github.com/google/fonts/tree/main/ofl/bowlbyone'),
    ('geist', 'Geist-variable.woff2', {'wght': 900}, 'Geist-OFL.txt', 'https://github.com/vercel/geist-font'),
    ('inter', 'Inter.ttf', {'opsz': 32, 'wght': 900}, 'Inter-OFL.txt', 'https://github.com/rsms/inter'),
]

class OutlinePen(BasePen):
    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.contours = []
        self.current = []

    def _moveTo(self, point):
        self.current = [point]

    def _lineTo(self, point):
        self.current.append(point)

    def _qCurveToOne(self, control, point):
        start = self.current[-1]
        for i in range(1, 19):
            t = i / 18
            u = 1 - t
            self.current.append(tuple(u*u*start[k] + 2*u*t*control[k] + t*t*point[k] for k in (0, 1)))

    def _curveToOne(self, a, b, point):
        start = self.current[-1]
        for i in range(1, 25):
            t = i / 24
            u = 1 - t
            self.current.append(tuple(u**3*start[k] + 3*u*u*t*a[k] + 3*u*t*t*b[k] + t**3*point[k] for k in (0, 1)))

    def _closePath(self):
        cleaned = []
        for point in self.current:
            if not cleaned or abs(point[0] - cleaned[-1][0]) + abs(point[1] - cleaned[-1][1]) > .0001:
                cleaned.append(point)
        if len(cleaned) > 1 and abs(cleaned[0][0] - cleaned[-1][0]) + abs(cleaned[0][1] - cleaned[-1][1]) < .0001:
            cleaned.pop()
        if len(cleaned) > 2:
            self.contours.append(cleaned)
        self.current = []

    def _endPath(self):
        self._closePath()


def area(points):
    return sum(a[0]*b[1] - b[0]*a[1] for a, b in zip(points, points[1:] + points[:1])) / 2


data, manifest = {}, []
for font_id, filename, axes, license_name, source in FONTS:
    path = ASSETS / filename
    font = TTFont(path)
    if axes:
        font = instantiateVariableFont(font, axes, inplace=False)
    glyph_set, cmap = font.getGlyphSet(), font.getBestCmap()
    cap = getattr(font['OS/2'], 'sCapHeight', 0) or font['head'].unitsPerEm * .7
    glyphs = {}
    for char in CHARS:
        name = cmap.get(ord(char))
        if not name:
            continue
        pen = OutlinePen(glyph_set)
        glyph_set[name].draw(pen)
        advance = font['hmtx'][name][0] / cap
        if not pen.contours:
            glyphs[char] = {'ratio': round(advance, 5), 'advance': round(advance, 5), 'contours': []}
            continue
        points = [p for contour in pen.contours for p in contour]
        x0, x1 = min(p[0] for p in points), max(p[0] for p in points)
        y0, y1 = min(p[1] for p in points), max(p[1] for p in points)
        w, h = max(.001, x1-x0), max(.001, y1-y0)
        contours = [[[(x-x0)/w, (y1-y)/h] for x, y in contour] for contour in pen.contours]
        # All sources share one nonzero convention: outer contours positive,
        # counters negative. Reverse the entire glyph if its largest is negative.
        if area(max(contours, key=lambda c: abs(area(c)))) < 0:
            contours = [list(reversed(c)) for c in contours]
        glyphs[char] = {
            'ratio': round(w/cap, 5), 'advance': round(advance, 5),
            'hasCounter': any(area(c) < 0 for c in contours),
            'contours': [[[round(x, 5), round(y, 5)] for x, y in c] for c in contours],
        }
    data[font_id] = glyphs
    manifest.append({
        'id': font_id, 'filename': filename, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
        'axes': axes, 'license': license_name, 'source': source,
    })

(OUTPUT / 'font-outlines.js').write_text('/** Generated by scripts/build-fonts.py. See licenses/ for font terms. */\nexport const FONT_OUTLINES=' + json.dumps(data, separators=(',', ':')) + ';\n')
(ROOT / 'assets' / 'font-manifest.json').write_text(json.dumps({'format': 'sampled normalized font outlines', 'license': 'SIL Open Font License 1.1', 'shaping': 'Independent Latin glyphs. No kerning, ligatures, script shaping, or Malayalam composition. The studio converts its input to uppercase.', 'fonts': manifest}, indent=2) + '\n')
print(f'Compiled {len(data)} font families / {sum(len(g) for g in data.values())} glyphs into {OUTPUT / "font-outlines.js"}')
